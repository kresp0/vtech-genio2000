#!/usr/bin/env python3
"""embed_layout.py <artwork_dir> <out.lay> [--optimize]
Turns the external-file photo layout of artwork/genio2000 (default.lay + PNG files) into a self-contained MAME *internal* layout: every
<image file="x.png" .../> becomes <image ...><data>base64 of x.png</data></image>, which MAME's layout loader decodes in memory (it detects
bitmap data, then falls back to SVG).  Nothing else in the layout is touched, so the appearance is identical.  --optimize first recompresses
the PNGs losslessly with optipng (pixels are identical; checked) to cut the size.
This is the proof of concept for the layout PR (docs/PR9_LAYOUT.md); the output file is src/mame/layout/genio2000.lay of the MAME tree."""
import sys, os, re, base64, shutil, subprocess, tempfile
from PIL import Image
import numpy as np
src, out = sys.argv[1], sys.argv[2]; opt = '--optimize' in sys.argv
text = open(os.path.join(src, 'default.lay'), encoding='utf-8').read()
tmp = tempfile.mkdtemp(); sizes = {}
def png_bytes(name):
    p = os.path.join(src, name)
    if opt:
        q = os.path.join(tmp, name); shutil.copy(p, q); subprocess.run(['optipng', '-quiet', '-o3', '-strip', 'all', q], check=True)
        a = np.asarray(Image.open(p).convert('RGBA')); b = np.asarray(Image.open(q).convert('RGBA')); assert np.array_equal(a, b), name + ': optimisation changed pixels'
        p = q
    d = open(p, 'rb').read(); sizes[name] = len(d); return d
def repl(m):
    attrs = (m.group(1) + m.group(3)).rstrip()
    b64 = base64.b64encode(png_bytes(m.group(2))).decode()
    wrapped = '\n'.join(b64[i:i + 96] for i in range(0, len(b64), 96))
    return '<image%s>\n<data>\n%s\n</data>\n</image>' % (' ' + attrs.strip() if attrs.strip() else '', wrapped)
n = len(re.findall(r'<image file="', text))
text = re.sub(r'<image((?:\s+\w+="[^"]*")*?)\s+file="([^"]+)"((?:\s+\w+="[^"]*")*)\s*/>', repl, text)
assert 'file=' not in text.replace('inputtag', ''), 'an image file reference is left'
LICENSE = os.environ.get('EMBED_LICENSE', 'PENDING-OWNER-DECISION')            # the owner chooses the licence and the copyright holder line; no default is assumed
HOLDERS = os.environ.get('EMBED_COPYRIGHT_HOLDERS', 'PENDING-OWNER-DECISION')
head = ('<?xml version="1.0"?>\n<!--\nlicense:%s\ncopyright-holders:%s\n' % (LICENSE, HOLDERS) +
        'Genio 2000 (Spain): photographic front panel (lid with the LCD window, keyboard and activity panel) with clickable keys.\n'
        'Photographs by the copyright holder; generated by tools/embed_layout.py from artwork/genio2000 (the images are PNG data, base64 encoded).\n'
        'The licence above covers the photographs and the images derived from them; trademarks, logos and designs of VTech that appear in them belong to their owners and are not covered by it.\n-->\n')
text = re.sub(r'^<\?xml[^>]*\?>\s*(<!--.*?-->)?\s*', head, text, count=1, flags=re.S)
open(out, 'w', encoding='utf-8').write(text)
print('embedded %d images (%s), wrote %s (%.1f MB)' % (n, ', '.join('%s %d' % kv for kv in sizes.items()), out, os.path.getsize(out) / 1e6))
