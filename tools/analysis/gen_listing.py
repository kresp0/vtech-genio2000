#!/usr/bin/env python3
"""Generate the annotated listing of every bank from out/insns.csv (+ curated names in names.json).

Per bank a file out/listing/bank<k>.asm is written, addressed in the bank's *primary* window:
  bank0 -> 0000, banks 5,7,6(code) -> 4000 where code was found there (bank 6 code also at 8000), data banks -> 8000.
Bytes not decoded as code are emitted as `.db` rows with an ASCII column; this is NOT a claim that they are data:
see ROM_MAP.md for the confidence of each region.
"""
import os, sys, csv, json, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
ROM = open(os.path.join(ROOT, 'rom', 'genio2000_es_128k.bin'), 'rb').read()
OUT = os.path.join(ROOT, 'out'); LST = os.path.join(OUT, 'listing'); os.makedirs(LST, exist_ok=True)
NAMES = json.load(open(os.path.join(ROOT, 'names.json'))) if os.path.exists(os.path.join(ROOT, 'names.json')) else {}
PORTS = {0: 'P_BANK0', 1: 'P_BANK1', 2: 'P_02', 3: 'P_BANK2', 4: 'P_04', 5: 'P_05', 6: 'P_06', 0x0A: 'P_LCD_CMD', 0x0B: 'P_LCD_DATA',
         0x10: 'P_KEY_COL', 0x11: 'P_KEY_ROW2', 0x12: 'P_SYS', 0xFE: 'P_FE?'}
PRIMARY = {0: 0x0000, 1: 0x8000, 2: 0x8000, 3: 0x8000, 4: 0x8000, 5: 0x4000, 6: 0x8000, 7: 0x4000}


def main():
    rows = collections.defaultdict(list)
    for r in csv.DictReader(open(os.path.join(OUT, 'insns.csv'))):
        rows[(int(r['bank']), int(r['window'], 16))].append(r)
    funcs = set()
    for r in csv.DictReader(open(os.path.join(OUT, 'functions.csv'))):
        funcs.add((int(r['bank']), int(r['window'], 16), int(r['addr'], 16)))
    targets = collections.defaultdict(set)
    for (k, w), lst in rows.items():
        for r in lst:
            if r['target']:
                t = int(r['target'], 16)
                tk, tw = (0, 0) if t < 0x4000 else (k, w)
                targets[(tk, tw)].add(t)
    stats = {}
    for k in range(8):
        base = PRIMARY[k]
        decoded = {}   # offset -> (row, window)
        wins = [w for (kk, w) in rows if kk == k]
        for (kk, w), lst in rows.items():
            if kk != k:
                continue
            for r in lst:
                a = int(r['addr'], 16)
                off = a if (k == 0 and w == 0) else a - w
                n = len(r['bytes']) // 2
                decoded.setdefault(off, (r, w, n))
        # remove instructions overlapped by an earlier-starting one (keep dynamic evidence first)
        order = sorted(decoded, key=lambda o: (-int(decoded[o][0]['dyn']), o))
        taken = {}
        for o in order:
            r, w, n = decoded[o]
            if any((o + j) in taken for j in range(n)):
                continue
            for j in range(n):
                taken[o + j] = o
        starts = sorted(set(taken.values()))
        out = open(os.path.join(LST, 'bank%d.asm' % k), 'w')
        out.write('; bank %d  primary window %04X  windows with code: %s\n' % (k, base, ','.join('%04X' % w for w in sorted(wins)) or 'none'))
        out.write('; generated by tools/gen_listing.py from out/insns.csv  --  decode = static trace + MAME execution (emulation) evidence\n')
        off = 0
        code_bytes = 0
        while off < 0x4000:
            if off in starts:
                r, w, n = decoded[off]
                la = (off + base) if (w == 0 or base == w or True) else 0
                addr = int(r['addr'], 16)
                lab = ''
                key = (0, 0, addr) if addr < 0x4000 else (k, w, addr)
                nm = NAMES.get('B%d@%04X:%04X' % key) if key in funcs or True else None
                nm = NAMES.get('%d:%04X' % (key[0], addr)) or nm
                if key in funcs:
                    out.write('\n; ---- fn_%04X %s\n' % (addr, ('(' + nm + ')') if nm else ''))
                    lab = 'fn_%04X:' % addr
                elif addr in targets[(key[0], key[1])]:
                    lab = 'l_%04X:' % addr
                text = r['text']
                cm = ''
                if text.startswith('out (') and text.endswith('),a'):
                    p = int(text[5:text.index(')')].replace('$', ''), 16)
                    cm = '; ' + PORTS.get(p, 'port %02X' % p)
                elif text.startswith('in a,('):
                    p = int(text[6:text.index(')')].replace('$', ''), 16) if text[6] == '$' else None
                    if p is not None:
                        cm = '; ' + PORTS.get(p, 'port %02X' % p)
                dyn = '*' if int(r['dyn']) else ' '
                out.write('%04X %s %-9s %-12s %-28s %s\n' % (addr, dyn, lab, r['bytes'], text, cm))
                code_bytes += n
                off += n
            else:
                # data run until next decoded start
                nxt = next((s for s in starts if s > off), 0x4000)
                end = min(nxt, 0x4000)
                o = off
                while o < end:
                    chunk = ROM[k * 0x4000 + o: k * 0x4000 + min(o + 16, end)]
                    asc = ''.join(chr(c) if 32 <= c < 127 else '.' for c in chunk)
                    out.write('%04X   .db %-48s ; %s\n' % (o + base, ','.join('%02X' % c for c in chunk), asc))
                    o += 16
                off = end
        out.close()
        stats[k] = code_bytes
    json.dump({'code_bytes_per_bank': stats, 'percent': {k: round(100 * v / 0x4000, 1) for k, v in stats.items()}}, open(os.path.join(OUT, 'listing_stats.json'), 'w'), indent=1)
    print(stats)


if __name__ == '__main__':
    main()
