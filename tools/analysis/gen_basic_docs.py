#!/usr/bin/env python3
"""Generate docs/BASIC_TOKENS.md and the keyword/statement tables of docs/BASIC_REFERENCE.md from the ROM (never hand-edited numbers)."""
import json, sys, os
sys.path.insert(0, 'tools'); import basic_tokens as bt
disp = {int(r['token'], 16): r for r in json.load(open('out/basic_statement_dispatch.json'))}
ents = bt.entries()
L = ["# BASIC_TOKENS: keyword and token table (generated by `tools/analysis/gen_basic_docs.py`)", "",
     "Structure (CONFIRMED, `B7:5650-581F`; read in the disassembly of `LIST`, `B7:6B94-6BC4`): the token `t>=0x80` is entry number `t-0x7F` of a",
     "contiguous list; each entry starts at a byte with bit 7 = 1 (first letter | 0x80) and continues with letters with bit 7 = 0. The 55 entries",
     "`81 00 ...` are **blanked** (keyword removed; they keep the token number and the padding of the table). The length of the padding",
     "(2-11 bytes) is that of the **assumed** original word; which word it was is not inferred (HYPOTHESIS).", "",
     "| Token | Entry address | Word | Raw bytes | Handler (statements) | Executed in MAME |", "|---|---|---|---|---|---|"]
for n, (addr, raw) in enumerate(ents):
    t = 0x80 + n; nm = bt.name(raw)
    d = disp.get(t)
    h = ('%s%s' % (d['handler'], ' (stub RAM)' if d['kind'] == 'ram_stub' else '')) if d else ''
    ex = d['executed_in_mame'] if d else ''
    L.append("| 0x%02X | B7:%04X | %s | `%s` | %s | %s |" % (t, addr, nm if nm else '*(blanked)*', raw.hex(), h, ex))
L += ["", "Notes: tokens 0x80-0xBB = statements (dispatch at `B7:5822`, 60 entries), 0xBC `TAB(`, 0xBD `TO`, 0xBF `USING`, 0xCA `THEN`, 0xCB `NOT`, 0xCC `STEP`,",
      "0xCD-0xD6 operators (`+ - * / ^ AND OR > = <`), 0xD7-0xFA functions. Tokens 0xFB-0xFF: no text entry (the table ends at `MID$`, 0x581F)."]
open('docs/BASIC_TOKENS.md', 'w').write('\n'.join(L) + '\n')
named = [(0x80 + n, bt.name(r)) for n, (_, r) in enumerate(ents) if bt.name(r)]
print(len(named), 'named keywords')
