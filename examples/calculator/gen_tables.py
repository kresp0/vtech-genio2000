import mpmath as mp

mp.mp.dps = 50
ND = 16


def digits(v, nd=ND):
    """(sign, e, digits) with value = sign * 0.d0d1.. * 10^e, rounded half up to nd digits"""
    v = mp.mpf(v)
    if v == 0:
        return 0, 0, [0] * nd
    s = 1 if v < 0 else 0
    v = abs(v)
    e = int(mp.floor(mp.log10(v))) + 1
    m = v / mp.power(10, e)
    if m >= 1:
        m /= 10; e += 1
    if m < mp.mpf('0.1'):
        m *= 10; e -= 1
    n = int(mp.floor(m * mp.power(10, nd) + mp.mpf('0.5')))
    if n >= 10 ** nd:
        n //= 10; e += 1
    return s, e, [int(c) for c in str(n).zfill(nd)]


def numlit(v, nd=ND):
    s, e, d = digits(v, nd)
    d = d + [0] * (ND - len(d))
    return "{%d, %d, {%s}}" % (s, e, ",".join(map(str, d)))


pi = mp.pi
CONSTS = [
    ("ONE", 1), ("ZERO", 0), ("HALF", mp.mpf('0.5')), ("1_5", mp.mpf('1.5')), ("E", mp.e),
    ("PI", pi), ("PI2", pi / 2), ("LN10", mp.log(10)), ("LN2", mp.log(2)),
    ("PI180", pi / 180), ("PI200", pi / 200), ("180PI", 180 / pi), ("200PI", 200 / pi),
    ("TAN15", 2 - mp.sqrt(3)), ("SQRT3", mp.sqrt(3)), ("HLN2PI", mp.log(2 * pi) / 2),
    ("2P32", 2 ** 32), ("2P31", 2 ** 31), ("1EM4", mp.mpf('1e-4')), ("1EM8", mp.mpf('1e-8')),
]
# Cody-Waite splits: k * A must be exact in 16 digits (k < 10^4 for ln10, q < 10^9 for pi/2)
LN10A = mp.mpf('2.302585092994')
PI2A = mp.mpf('1.570796')
STIR = [mp.mpf(1) / 12, mp.mpf(-1) / 360, mp.mpf(1) / 1260, mp.mpf(-1) / 1680, mp.mpf(1) / 1188,
        mp.mpf(-691) / 360360, mp.mpf(1) / 156, mp.mpf(-3617) / 122400]
GLX = [-mp.sqrt(5 + 2 * mp.sqrt(mp.mpf(10) / 7)) / 3, -mp.sqrt(5 - 2 * mp.sqrt(mp.mpf(10) / 7)) / 3, 0]
GLX += [-GLX[1], -GLX[0]]
GLW = [(322 - 13 * mp.sqrt(70)) / 900, (322 + 13 * mp.sqrt(70)) / 900, mp.mpf(128) / 225]
GLW += [GLW[1], GLW[0]]

# function names; the order sets the F_ ids (see eval.h: one argument, then F_TWO.., then the calculus ones)
ONE_ARG = "sin cos tan asin acos atan sinh cosh tanh asinh acosh atanh ln log abs int frac floor rnd gamma not".split()
ZERO_ARG = "e rand".split()
TWO_ARG = "ncr npr gcd lcm mod max min ranint and or xor".split()
CALC = ["solve"]            # then F_INTEG, F_SIGMA, F_DERIV: symbols, no name


KLIST = CONSTS + [("LN10A", LN10A), ("LN10B", mp.log(10) - LN10A), ("PI2A", PI2A), ("PI2B", pi / 2 - PI2A)]
KLIST += [(n, mp.mpf(n.replace("M", "-").replace("1E", "1e"))) for n in
          "1E3 1E4 1E6 1E9 1E15 1EM3 1EM10 1EM12 1EM14 1EM24 1EM40 1EM60".split()]
KLIST += [("ST%d" % i, v) for i, v in enumerate(STIR)] + [("GLX%d" % i, v) for i, v in enumerate(GLX)]
KLIST += [("GLW%d" % i, v) for i, v in enumerate(GLW)]
KINDEX = {n: i for i, (n, v) in enumerate(KLIST)}
NAMES = ONE_ARG + ZERO_ARG + TWO_ARG + CALC


def gen_consts():
    o = ["// generated by gen_tables.py"]
    for n in ("ONE", "HALF", "PI", "2P31", "2P32"):     # the ones the C code uses; the microcode reads page 2
        o.append("static const num K_%s = %s;" % (n, numlit(dict(KLIST)[n])))
    for i, n in enumerate(NAMES):
        o.append("#define F_%s %d" % (n.upper(), i))
    o.append("#define F_TWO F_%s" % TWO_ARG[0].upper())
    o.append("#define F_INTEG %d\n#define F_SIGMA %d\n#define F_DERIV %d" % (len(NAMES), len(NAMES) + 1, len(NAMES) + 2))
    o.append('static const char fn_names[] = "%s\\0";' % "\\0".join(NAMES))
    return "\n".join(o) + "\n"


def numbytes(v):
    s, e, d = digits(v)
    return bytes([s]) + (e & 0xFFFF).to_bytes(2, "little") + bytes(d)


def page2(code, tables):
    """the data page (selector 0x83): microcode, its constants (19 bytes each), address tables and strings"""
    img = bytearray(b"CALC")
    defs = ["// generated by gen_tables.py: page 2 layout (addresses in the 8000-BFFF window)",
            "#define P2_VM 0x%04X" % (0x8000 + len(img))]
    img += bytes(code)
    defs.append("#define P2_KT 0x%04X" % (0x8000 + len(img)))
    for n, v in KLIST:
        img += numbytes(v)
    blobs = []
    for name, items in tables.items():
        defs.append("#define P2_%s 0x%04X" % (name, 0x8000 + len(img)))
        for it in items:
            blobs.append((len(img), it))
            img += b"\0\0"
    for at, it in blobs:
        a = 0x8000 + len(img)
        img[at:at + 2] = a.to_bytes(2, "little")
        img += bytes(it) + b"\0"
    defs.append("#define P2_USED %d" % len(img))
    assert len(img) <= 0x4000 - 128, "page 2 is full"
    img += b"\xff" * (0x4000 - len(img))
    return img, "\n".join(defs) + "\n"


if __name__ == "__main__":
    assert len(ONE_ARG) + len(ZERO_ARG) < 255
    import gen_vm
    import gen_ui
    vm, code = gen_vm.gen(KINDEX, NAMES)
    open("consts.h", "w").write(gen_consts() + vm)
    ui, tables = gen_ui.gen()
    img, defs = page2(code, tables)
    open("tables.h", "w").write(ui + defs)
    open("page2.bin", "wb").write(img)
    open("tests/page2.h", "w").write("static const byte page2[16384] = {%s};\n" % ",".join(map(str, img)))
    print("microcode %d bytes, page 2: %s" % (len(code), defs.split()[-1]))
