"""helpers.h: auxiliary assembly routines (outside the loop): fetch_note, build_tab, build_wob"""
def write_helpers(SPI0, SPI, TAB0, BITS, WOB, path='helpers.h'):
    unpack = ''.join('''\tld a, (hl)
\tinc hl
\tld c, a
\tld b, #8
%d$:\tld a, #0
\trl c
\tadc a, #0
\tld (de), a
\tinc de
\tdjnz %d$
''' % (k + 1, k + 1) for k in range(5))
    txt = '''// generated by gen_helpers.py (do not edit)
void fetch_note() __naked {
__asm
	ld hl, (_song_ptr)
	ld e, (hl)
	inc hl
	ld d, (hl)
	inc hl
	ld a, (hl)
	inc hl
	ld (_song_ptr), hl
	ld c, a
	ld a, d
	and a, e
	inc a
	jr z, fn_term
	; LED (bit 5 of port 0x12) following the music: IXL = odd samples, IXH = even (brightness 0, medium, full)
	.db 0xDD, 0x2E, 0
	.db 0xDD, 0x26, 0
	ld a, (_led_off)
	or a, a
	jr nz, fn_led
	ld a, (_gen)
	or a, a
	jr z, fn_kick
	ld a, d			; scenes with a sweep: the brightness grows with the pitch
	cp a, #1
	jr c, fn_led
	.db 0xDD, 0x26, 0x20
	cp a, #3
	jr c, fn_led
	.db 0xDD, 0x2E, 0x20
	jr fn_led
fn_kick:			; bass (kick/bass line): LED on
	ld a, d
	cp a, #2
	jr nc, fn_led
	or a, a
	jr nz, fn_on
	ld a, e
	cp a, #55
	jr c, fn_led
fn_on:	.db 0xDD, 0x2E, 0x20
	.db 0xDD, 0x26, 0x20
fn_led:
	ld a, (_gen)
	or a, a
	jr z, fn_nogen
	push de
	push bc
	ld c, d
	ld hl, #0x%(SPI0)04X
	ld de, #0x%(SPI)04X
	ld b, #8
fn_g1:	ld a, (hl)
	add a, c
	ld (de), a
	inc l
	inc e
	djnz fn_g1
	pop bc
	pop de
fn_nogen:
	ld b, #0
	ld h, b
	ld l, c
	add hl, hl
	add hl, hl
	add hl, hl
	ld b, h
	ld c, l
	add hl, hl
	add hl, bc
	ld b, h
	ld c, l
	ld hl, #0
	ret
fn_term:
	ld a, #1
	ld (_done), a
	ld de, #0
	ld bc, #0xffff
	ld hl, #0
	.db 0xDD, 0x2E, 0
	.db 0xDD, 0x26, 0
	ret
__endasm;
}

void build_tab() __naked {
__asm
	ld hl, (_tab_src)
	ld a, #8
	ld (_bt_row), a
	ld a, #0x%(TABPG)02X
	ld (_bt_pg), a
bt_row:
	ld de, #0x%(BITS)04X
%(unpack)s	ld (_bt_src), hl
	ld hl, #0x%(BITS)04X
	ld de, #0x%(BITS40)04X
	ld bc, #44
	ldir
	ld hl, #0x%(BITS)04X
	ld b, #5
	xor a, a
bt_w0:	add a, a
	or a, (hl)
	inc hl
	djnz bt_w0
	ld c, a
	ld a, (_bt_pg)
	ld d, a
	ld e, #0
	ld a, c
	ld b, #80
bt_win:	ld (de), a
	add a, a
	and a, #0x1f
	or a, (hl)
	inc hl
	inc e
	djnz bt_win
	ld a, (_bt_pg)
	inc a
	ld (_bt_pg), a
	ld hl, (_bt_src)
	ld a, (_bt_row)
	dec a
	ld (_bt_row), a
	jp nz, bt_row
	ret
__endasm;
}

void build_wob() __naked {
__asm
	ld hl, #_sine_tab
	ld de, #0x%(WOB)04X
	ld a, (_wob_sh)
	ld c, a
bw_loop:
	ld a, (hl)
	inc hl
	ld b, c
	inc b
bw_sh:	dec b
	jr z, bw_st
	srl a
	jr bw_sh
bw_st:	ld (de), a
	inc e
	jr nz, bw_loop
	ret
__endasm;
}
''' % dict(SPI0=SPI0, SPI=SPI, TABPG=TAB0 >> 8, BITS=BITS, BITS40=BITS + 40, WOB=WOB, unpack=unpack)
    open(path, 'w').write(txt)
