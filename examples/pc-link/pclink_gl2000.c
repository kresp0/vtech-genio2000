#define STUCK_RESET 80		// receive calls with the line low (about 2 s): back to the default rate
#define BAUD_DEFAULT BAUD_76800
#define CAP_SKEW  (-13)	// rising changes as seen on the owner's unit by the scope (2026-11-13): 12 T early

