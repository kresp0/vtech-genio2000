/*
	pclink_gl2000 - PC -> Genio serial link test cartridge for the VTech Genio 2000 / Genius LEADER 4000 family

	Receives a bit-banged UART on the printer BUSY line (DB25 pin 11, port 0x11 bit 5) and answers on DATA0
	(DB25 pin 2, port 0x10), at 2400, 4800, 9600 or 19200 baud 8N1. A burst that is a valid packet
	(A5 5A type seq len payload CRC-16) gets an ACK/NAK packet back; anything else is shown as text and echoed.
	Interrupts stay disabled: the receive and transmit routines (serial.h, generated by gen_serial.py) count T-states.
	Port 0x12 is never written except by the power-off routine; the keyboard scan skips column 0 so that DATA0
	stays at the idle level between transmissions.
	cart_crt0.s does not run gsinit: globals are assigned before use.
	Copyright (c) 2026 Santiago Crespo. GPL-3.0-or-later (built against VGLDK)
*/
